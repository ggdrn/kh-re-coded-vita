#!/usr/bin/env python3
"""Re:coded Vita build. Game compiler flags also feed the native portability audit."""
import argparse
import os
import shlex
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT / "tools"))

TITLE = "Kingdom Hearts Re:coded"
TITLE_ID = "KHRC00001"

VITASDK = Path(os.environ.get("VITASDK", Path.home() / "vitasdk"))
BIN = VITASDK / "bin"

# The game code is compiled for the Cortex-A9 in ARM mode. -fsigned-char and -fshort-enums off
# (int enums) follow mwccarm's settings in the decomp's configure.py (-char signed, -enum int),
# so structs keep the layout the original compiler gave them. gnu11: the decomp relies on
# unprototyped `extern int f();` declarations, which C23 would read as `f(void)`.
COMMON_CFLAGS = [
    "-mcpu=cortex-a9", "-mfpu=neon", "-marm", "-mfloat-abi=hard",
    "-fsigned-char", "-fno-short-enums", "-fno-strict-aliasing", "-fwrapv",
    "-ffunction-sections", "-fdata-sections", "-g",
    "-DPLATFORM_VITA=1",
]
PORT_CFLAGS = ["-std=gnu11", "-O3", "-Wall", "-Wno-unused-function", "-funwind-tables"]
GAME_CFLAGS = [
    "-std=gnu11", "-O2", "-w", "-funwind-tables",
    # locals the ROM reads before setting (it gets whatever the register held) are 0: GCC would
    # otherwise treat such a read as any value it likes and fold branches on it
    "-ftrivial-auto-var-init=zero",
    # objects in source order, as mwcc emits them: the decomp's data files list a module's
    # objects in DS address order, and code reads from one into the next (tools/check_layout.py)
    "-fno-toplevel-reorder",
    # The decomp's K&R-style calls and int<->pointer casts are deliberate: mwccarm accepted
    # them, and GCC 14+ turns these diagnostics into errors by default.
    "-Wno-error=implicit-function-declaration", "-Wno-error=int-conversion",
    "-Wno-error=incompatible-pointer-types", "-Wno-error=implicit-int",
    "-Wno-error=return-mismatch",
]

GAME_CXXFLAGS = ["-std=gnu++11", "-O2", "-w", "-ftrivial-auto-var-init=zero", "-fno-exceptions", "-funwind-tables",
                 "-fno-toplevel-reorder", "-fpermissive"]

LIBS = [
    "-lvitaGL", "-lvitashark", "-lSceShaccCgExt", "-lmathneon", "-lstdc++", "-lm", "-lc",
    "-lkubridge_stub_weak", "-lSceVshBridge_stub", "-ltaihen_stub", "-lSceShaccCg_stub", "-lSceKernelDmacMgr_stub",
    "-lSceCommonDialog_stub", "-lSceGxm_stub", "-lSceDisplay_stub", "-lSceAppMgr_stub",
    "-lSceAppUtil_stub", "-lSceCtrl_stub", "-lSceTouch_stub", "-lSceAudio_stub",
    "-lScePower_stub", "-lSceRtc_stub", "-lSceKernelModulemgr_stub", "-lSceSysmodule_stub", "-lSceLibKernel_stub",
]


def main():
    ap = argparse.ArgumentParser(description="Build the Re:coded Vita diagnostic shell")
    ap.add_argument("--with-game", action="store_true", help="generate build/native-vpk.ninja for the linked game runtime")
    ap.add_argument("--native-objects", action="store_true", help="compile native units and retain failures/objects")
    ap.add_argument("--native-link", action="store_true", help="diagnostic relocatable link, not a VPK")
    args = ap.parse_args()
    if args.native_objects:
        sys.exit(subprocess.call([sys.executable, str(ROOT / "tools/compile_native.py")]))
    if args.native_link:
        sys.exit(subprocess.call([sys.executable, str(ROOT / "tools/link_native.py")]))
    version = (ROOT / "VERSION").read_text().strip()
    major, minor, patch = map(int, version.split("."))
    # APP_VER is XX.YY on the Vita: the minor and patch numbers share YY (capped at 99)
    app_ver = f"{major:02d}.{min(minor * 100 + patch, 99):02d}"
    # the LiveArea bubble shows the version, so the console says which build is installed;
    # the TITLE_ID stays the same: every build replaces the one bubble
    title = f"{TITLE} v{version}"
    short_title = f"Re:coded v{version}"
    q = lambda xs: " ".join(shlex.quote(str(x)) for x in xs)
    esc = lambda p: str(p).replace("$", "$$").replace(" ", "$ ")
    sources = sorted([*(ROOT / "platform/core").glob("*.c"), *(ROOT / "platform/audio").glob("*.c")])
    includes = ["-Iplatform/core", "-Iplatform", "-Iplatform/compat"]
    lines = ["# Generated by configure_vita.py", "ninja_required_version = 1.10",
             "cc = " + q([BIN / "arm-vita-eabi-gcc"]),
             "cflags = " + q(COMMON_CFLAGS + PORT_CFLAGS + [f'-DKH_VERSION="{version}"'] + includes),
             "libs = " + q(LIBS)]
    def rule(name, command):
        lines.extend([f"rule {name}", "  command = " + command, f"  description = {name.upper()} $out"])
    rule("cc", "$cc $cflags -MMD -MF $out.d -c $in -o $out")
    lines.extend(["  depfile = $out.d", "  deps = gcc"])
    rule("link", "python3 tools/link_vita_elf.py $cc $out -Wl,-q -Wl,--gc-sections -Wl,--no-enum-size-warning $in $libs && python3 tools/check_elf.py $out || (rm -f $out; false)")
    rule("velf", q([BIN / "vita-elf-create"]) + " $in $out")
    rule("fself", q([BIN / "vita-make-fself"]) + " -c $in $out")
    rule("sfo", q([BIN / "vita-mksfoex", "-s", "TITLE_ID=" + TITLE_ID, "-s", "APP_VER=" + app_ver,
                    "-s", "STITLE=" + short_title, "-d", "ATTRIBUTE2=12", title]) + " $out")
    from tools.make_livearea import SIZES

    local_art = sorted({path.relative_to(ROOT).as_posix()
                        for rel in SIZES
                        for path in (ROOT / "art_src").glob(Path(rel).stem + ".*")
                        if path.is_file()})
    art_dir = "build/livearea/sce_sys" if local_art else "sce_sys"
    art = [rel for rel in SIZES if rel != "pic0.png"]
    if any(Path(path).stem == "pic0" for path in local_art):
        art.append("pic0.png")
    rule("livearea", f"python3 tools/make_livearea.py {art_dir}" + (" --from art_src" if local_art else ""))
    art_files = [f"{art_dir}/{rel}" for rel in art]
    template = "sce_sys/livearea/contents/template.xml"
    title_art = []
    for (stem_name, target) in (("bg", "bg.png"), ("startup", "logo.png")):
        if any(Path(path).stem == stem_name for path in local_art):
            title_art += ["-a", f"{art_dir}/livearea/contents/{stem_name}.png=assets/titlescreen/{target}"]
    rule("vpk", q([BIN / "vita-pack-vpk"]) + " -s build/param.sfo -b $in " +
         q(["-a", f"{template}={template}"] +
           [arg for rel in art for arg in ("-a", f"{art_dir}/{rel}=sce_sys/{rel}")] + title_art) + " $out")
    if args.with_game:
        native = "build/native"
        objects = [native + "/recoded.sdk.o"]
        stem = native + "/khrecoded"
        eboot = native + "/eboot.bin"
        rule("sdk", "python3 tools/link_native_sdk.py")
        lines.append(f"build {native}/recoded.sdk.o: sdk {native}/recoded.partial.o | tools/link_native_sdk.py")
    else:
        objects = []
        stem = "build/khrecoded"
        eboot = "build/eboot.bin"
    for source in ([] if args.with_game else sources):
        relative = source.relative_to(ROOT)
        obj = "build/port/" + str(relative.with_suffix(".o"))
        objects.append(obj)
        lines.append(f"build {esc(obj)}: cc {esc(relative)}")
    lines.extend([
        f"build {stem}.elf: link " + " ".join(map(esc, objects)),
        f"build {stem}.velf: velf {stem}.elf",
        f"build {eboot}: fself {stem}.velf",
        "build build/param.sfo: sfo | VERSION",
        "build " + " ".join(art_files) + ": livearea | " +
        " ".join(map(esc, ["tools/make_livearea.py", *local_art])),
    ])
    suffix = "-native" if args.with_game else ""
    vpk = f"build/VPK/recoded_v{version}.vpk" if args.with_game else f"build/VPK/khrecoded-vita-{version}{suffix}.vpk"
    lines.extend([f"build {vpk}: vpk {eboot} | build/param.sfo " + " ".join(art_files + [template]),
                  f"default {vpk}"])
    (ROOT / ("build/native-vpk.ninja" if args.with_game else "build.ninja")).write_text("\n".join(lines) + "\n")
    print(f"VPK target: {vpk}")

if __name__ == "__main__":
    main()
